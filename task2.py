# Integer
zahl = 10
print("Integer:", zahl)
print("Type:", type(zahl))

# Float
kommazahl = 10.5
print("\nFloat:", kommazahl)
print("Type:", type(kommazahl))

# String
text = "Hello, World!"
print("\nString:", text)
print("Type:", type(text))

# Boolean
wahrheitswert = True
print("\nBoolean:", wahrheitswert)
print("Type:", type(wahrheitswert))
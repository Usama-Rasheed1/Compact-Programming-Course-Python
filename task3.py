# Original values
integer_num = 10
float_num = 15.7
string_num = "25"

# 1. Integer to Float
int_to_float = float(integer_num)
print("Integer to Float:", int_to_float)

# 2. Float to Integer
float_to_int = int(float_num)
print("Float to Integer:", float_to_int)

# 3. Integer to String
int_to_string = str(integer_num)
print("Integer to String:", int_to_string)

# 4. String to Integer
string_to_int = int(string_num)
print("String to Integer:", string_to_int)

# 5. Integer to Boolean
int_to_bool = bool(integer_num)
print("Integer to Boolean:", int_to_bool)